// Pulls the page-text defaults and the "happy to help with" list out of Atharva's admin.html
// and writes them to admin-data.js (used by the real admin screens).
// Run after an artifact update changes the words:  node tools/extract-admin-data.js .
const fs = require('fs'), vm = require('vm');
const root = process.argv[2] || '.';
const src = fs.readFileSync(root + '/admin.html', 'utf8');
const grab = (re, what) => { const m = re.exec(src); if (!m) throw new Error('not found in admin.html: ' + what); return m[0]; };
const seed = grab(/^const SEED = .*$/m, 'SEED');
const docsrc = grab(/^const DOCSRC = .*$/m, 'DOCSRC');
const a = src.indexOf('const LG = DOCSRC.DOCS;'), b = src.indexOf('const PG = {};');
if (a < 0 || b < 0) throw new Error('PAGES block not found');
const ctx = {};
vm.createContext(ctx);
vm.runInContext(seed + '\n' + docsrc + '\n' + src.slice(a, b) + '\nthis.OUT = {PAGES: PAGES, OPEN: SEED.OPEN, OPEN_FOR: SEED.OPEN_FOR};', ctx);
const out = JSON.parse(JSON.stringify(ctx.OUT));
// the footer note is the prototype's "every person here is invented" line, which the live site hides on purpose
// these sentences are not a line of their own on the live site (they sit inside longer text, or the live page words them differently),
// so an edit could never show up there. They are left out of the editor so nothing in it silently does nothing.
const NOT_ON_SITE = { login: ['help', 'fac'], faculty: ['forgot', 'notice'], join: ['stu', 'alum'], directory: ['b1', 'contact'] };
out.PAGES.forEach(p => { if (NOT_ON_SITE[p.id]) p.f = p.f.filter(f => NOT_ON_SITE[p.id].indexOf(f[0]) < 0); });
out.PAGES.forEach(p => { if (p.id === 'footer') p.f = p.f.filter(f => f[0] !== 'note'); });
fs.writeFileSync(root + '/admin-data.js', '/* generated by tools/extract-admin-data.js from admin.html, do not edit by hand */\nwindow.BADMIN_DATA = ' + JSON.stringify(out) + ';\n');
console.log('admin-data.js written: ' + out.PAGES.length + ' pages, ' + out.OPEN.length + ' help topics');
